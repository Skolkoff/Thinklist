export const detectLocale = (): Locale => {
  if (typeof navigator === 'undefined') return 'en';

  const languages = navigator.languages?.length ? navigator.languages : [navigator.language];
  return languages.some(language => language.toLowerCase().startsWith('ru')) ? 'ru' : 'en';
};

export const resolveLocale = (preference: LanguagePreference | undefined | null): Locale => {
  if (preference === 'en' || preference === 'ru') return preference;
  return detectLocale();
};

export const t = (
  locale: Locale,
  key: TranslationKey,
  params: Record<string, string | number> = {}
): string => {
  const template = translations[locale]?.[key] || translations.en[key] || key;
  return Object.entries(params).reduce(
    (value, [name, replacement]) => value.replaceAll(`{{${name}}}`, String(replacement)),
    template
  );
};

export const getTopicLabel = (tag: string, locale: Locale): string => {
  const exact = topicLabels[tag]?.[locale] || topicLabels[tag]?.en;
  if (exact) return exact;

  const prefix = topicPrefixLabels.find(item => tag.startsWith(item.prefix));
  if (prefix) {
    const suffix = tag
      .slice(prefix.prefix.length)
      .replaceAll('-', ' ')
      .replaceAll('_', ' ')
      .toUpperCase();
    return `${prefix[locale]}: ${suffix}`;
  }

  if (tag.startsWith('cs.')) {
    return locale === 'ru' ? `Информатика: ${tag.slice(3)}` : `Computer Science: ${tag.slice(3)}`;
  }

  return tag;
};

export const getTopicChipLabel = (tag: string, locale: Locale): string => {
  if (locale === 'ru' && topicLabels[tag]?.shortRu) {
    return topicLabels[tag].shortRu;
  }

  return getTopicLabel(tag, locale);
};
